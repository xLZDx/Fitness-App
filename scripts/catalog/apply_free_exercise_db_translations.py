def translate(source_id: str) -> tuple[str, list[str], int, list[str]]:
    if source_id not in TRANSLATIONS:
        raise KeyError(f'no Russian translation staged for {source_id}')
    return TRANSLATIONS[source_id]


def main() -> None:
    staged = json.loads(STAGING.read_text('utf-8'))
    assert len(staged) == len(TRANSLATIONS), (
        f'staged {len(staged)} exercises but have {len(TRANSLATIONS)} '
        f'translations -- every staged entry must be translated')

    exercises = json.loads((CATALOG_DIR / 'exercises.json').read_text('utf-8'))
    ru_overlay = json.loads(
        (CATALOG_DIR / 'exercises.ru.json').read_text('utf-8'))
    existing_ids = {e['id'] for e in exercises}

    added = 0
    for src in staged:
        sid = src['source_id']
        new_id = f'fedb_{sid.lower()}'
        if new_id in existing_ids:
            continue
        ru_title, ru_steps, minutes, contra = translate(sid)

        primary = [MUSCLE_MAP[m] for m in src['primaryMuscles']
                   if MUSCLE_MAP.get(m)]
        secondary = [MUSCLE_MAP[m] for m in src['secondaryMuscles']
                     if MUSCLE_MAP.get(m)]
        muscles = list(dict.fromkeys(primary + secondary))  # de-dup, ordered

        exercises.append({
            'id': new_id,
            'title': src['name'],
            'equipmentId': src['equipmentId'],
            'muscles': muscles,
            'primaryMuscles': primary,
            'difficulty': LEVEL_MAP.get(src['level'], 'beginner'),
            'durationMinutes': minutes,
            'summary': src['instructions'][0] if src['instructions'] else '',
            'steps': src['instructions'],
            'frames': [],  # real photos are network URLs, not bundled demo
            'contraindications': contra,
            'imageUrls': src['images'],  # NEW field, network-hosted stills
        })
        ru_overlay[new_id] = {'title': ru_title, 'steps': ru_steps}
        added += 1

    (CATALOG_DIR / 'exercises.json').write_text(
        json.dumps(exercises, ensure_ascii=False, indent=1) + '\n', 'utf-8')
    (CATALOG_DIR / 'exercises.ru.json').write_text(
        json.dumps(ru_overlay, ensure_ascii=False, indent=1) + '\n', 'utf-8')
    print(f'added {added} exercises; catalog now has {len(exercises)} total')


if __name__ == '__main__':
    main()
