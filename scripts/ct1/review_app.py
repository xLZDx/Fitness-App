"""CT-1 — generates the reviewer's interface, one self-contained page per slot.

    python scripts/ct1/review_app.py --batch core/ml/review/ct1_review_batch_002

Output is a single HTML file per reviewer slot with that slot's items embedded.
No server, no build step, no network: a reviewer opens the file, answers, and
presses Export. That is not minimalism for its own sake — a review tool that
needs infrastructure to run is a review tool that does not get run, and the
whole CT-1 gate is blocked on somebody actually doing this work.

## What the page must not contain, and why it is tested rather than intended

The page is what a reviewer sees, so it is where blindness either holds or
fails. It carries the catalogue content and the question vocabulary. It does
NOT carry: the deterministic baseline's verdict for the row, the name of any
rule that fired, any model prediction or score, any other reviewer's answer, or
the fact that the row is also assigned to somebody else.

Each of those leaks the same way: it converts the reviewer from someone
producing an independent label into someone confirming or contesting an existing
one, and a confirmation rate is not a label. ``test_review_app`` scans the
GENERATED BYTES for the vocabulary rather than trusting this docstring, because
the failure mode is a template picking up a field somebody added upstream.

## What it stores

``localStorage``, keyed by batch and slot, written on every change. A reviewer
gets through 180 rows over more than one sitting, and losing an afternoon's work
to a closed tab is how a batch stops being finished. Export writes a submission
file that ``review_import`` validates; the page itself validates nothing beyond
prompting, because a page that silently corrects a submission is a page that
decides what the label is.
"""
