JS = r"""
const P = JSON.parse(document.getElementById('payload').textContent);
const KEY = 'ct1:' + P.batch_id + ':' + P.slot;
let state = {};
try { state = JSON.parse(localStorage.getItem(KEY) || '{}'); } catch (e) { state = {}; }
let cur = 0;

// Quotes are escaped too, although no vendor-controlled value currently
// reaches an attribute. Every `="${...}"` slot below interpolates a code
// constant or a loop index, and a test pins those vocabularies to
// `[a-z][a-z0-9_]*` so a quote cannot appear in one -- that is what makes the
// attribute contexts safe. This is the belt: it means the property survives
// somebody adding a catalogue field to an attribute later, rather than
// depending on nobody doing so.
const esc = s => String(s == null ? '' : s).replace(/[&<>"']/g,
  c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));

function rec(id) {
  if (!state[id]) state[id] = { answers: {}, reason_codes: [], note: '',
                                needs_domain_review: false, review_status: null };
  return state[id];
}
function complete(id) {
  const r = state[id];
  if (!r) return false;
  if (r.review_status === 'SKIPPED') return true;
  return P.questions.every(q => r.answers[q.id]);
}
function save() { localStorage.setItem(KEY, JSON.stringify(state)); paintNav(); }

function paintNav() {
  const n = document.getElementById('nav');
  n.innerHTML = P.items.map((it, i) =>
    `<button data-i="${i}" class="${complete(it.item_id) ? 'done' : ''} ${i === cur ? 'cur' : ''}">`
    + `${i + 1}. ${esc(it.title || it.item_id)}</button>`).join('');
  const done = P.items.filter(it => complete(it.item_id)).length;
  document.getElementById('progress').textContent =
    done + ' / ' + P.items.length + ' answered';
}

function paint() {
  const it = P.items[cur], r = rec(it.item_id);
  const ru = it.ru || {};
  const list = (label, arr) => (arr && arr.length)
    ? `<h3>${label}</h3><ol>${arr.map(s => `<li>${esc(s)}</li>`).join('')}</ol>` : '';
  document.getElementById('content').innerHTML =
    `<h2>${esc(it.title)}</h2>`
    + `<p class="muted">${esc(it.item_id)}</p>`
    + (it.summary ? `<p>${esc(it.summary)}</p>` : '')
    + list('Steps', it.steps)
    + ((it.tips && it.tips.length)
        ? `<h3>Tips</h3><ul>${it.tips.map(s => `<li>${esc(s)}</li>`).join('')}</ul>` : '')
    + `<h3>Metadata</h3><dl>`
    + `<dt>Equipment</dt><dd>${esc(it.equipment_id) || '<span class="muted">none</span>'}</dd>`
    + `<dt>Muscles</dt><dd>${esc((it.muscles || []).join(', ')) || '<span class="muted">none</span>'}</dd>`
    + `<dt>Difficulty</dt><dd>${esc(it.difficulty) || '<span class="muted">none</span>'}</dd>`
    + `<dt>Stretch</dt><dd>${it.is_stretch ? 'yes' : 'no'}</dd></dl>`
    + `<h3>Russian</h3>`
    + (Object.keys(ru).length
        ? `<p><b>${esc(ru.title)}</b></p>` + (ru.summary ? `<p>${esc(ru.summary)}</p>` : '')
          + list('', ru.steps)
        : `<p class="muted">no Russian row</p>`);

  document.getElementById('questions').innerHTML = P.questions.map(q =>
    `<div class="q"><p>${esc(q.text)}</p><div class="opts">`
    + P.verdicts.map(v =>
        `<label><input type="radio" name="${q.id}" value="${v.id}"`
        + `${r.answers[q.id] === v.id ? ' checked' : ''}><span>${esc(v.text)}</span></label>`
      ).join('')
    + `</div></div>`).join('');

  document.getElementById('reasons').innerHTML = P.reasons.map(c =>
    `<label><input type="checkbox" value="${c.id}"`
    + `${r.reason_codes.includes(c.id) ? ' checked' : ''}> ${esc(c.text)}</label>`).join('');

  document.getElementById('note').value = r.note || '';
  document.getElementById('domain').checked = !!r.needs_domain_review;
  document.getElementById('pos').textContent = (cur + 1) + ' of ' + P.items.length;
  paintNav();
  window.scrollTo(0, 0);
}

document.getElementById('nav').addEventListener('click', e => {
  const b = e.target.closest('button'); if (!b) return;
  cur = +b.dataset.i; paint();
});
document.getElementById('questions').addEventListener('change', e => {
  const r = rec(P.items[cur].item_id);
  r.answers[e.target.name] = e.target.value;
  r.review_status = 'COMPLETE';
  save();
});
document.getElementById('reasons').addEventListener('change', () => {
  const r = rec(P.items[cur].item_id);
  r.reason_codes = [...document.querySelectorAll('#reasons input:checked')].map(i => i.value);
  save();
});
document.getElementById('note').addEventListener('input', e => {
  rec(P.items[cur].item_id).note = e.target.value; save();
});
document.getElementById('domain').addEventListener('change', e => {
  rec(P.items[cur].item_id).needs_domain_review = e.target.checked; save();
});
document.getElementById('skip').addEventListener('click', () => {
  const r = rec(P.items[cur].item_id);
  r.review_status = 'SKIPPED'; r.answers = {};
  save(); paint();
});
document.getElementById('prev').addEventListener('click', () => {
  if (cur > 0) { cur--; paint(); }
});
document.getElementById('next').addEventListener('click', () => {
  if (cur < P.items.length - 1) { cur++; paint(); }
});

document.getElementById('export').addEventListener('click', () => {
  const now = new Date().toISOString();
  const reviews = [];
  for (const it of P.items) {
    const r = state[it.item_id];
    if (!r || !r.review_status) continue;   // never opened: stays UNKNOWN
    const status = r.review_status === 'SKIPPED' ? 'SKIPPED'
      : (P.questions.every(q => r.answers[q.id]) ? 'COMPLETE' : null);
    if (!status) continue;                  // partially answered: not a review
    reviews.push({
      item_id: it.item_id,
      source_content_version: it.source_content_version,
      review_timestamp: r.at || now,
      review_status: status,
      answers: status === 'SKIPPED' ? {} : r.answers,
      reason_codes: r.reason_codes || [],
      note: r.note || '',
      needs_domain_review: !!r.needs_domain_review
    });
  }
  const who = document.getElementById('who').value.trim();
  const out = {
    batch_id: P.batch_id,
    review_schema_version: P.review_schema_version,
    reviewer: who,
    reviewer_slot: P.slot,
    reviewer_kind: 'HUMAN',
    submitted_at: now,
    reviews: reviews
  };
  const text = JSON.stringify(out, null, 2);
  const box = document.getElementById('out');
  box.value = text; box.hidden = false; box.select();
  const a = document.getElementById('dl');
  a.href = URL.createObjectURL(new Blob([text], { type: 'application/json' }));
  a.download = P.batch_id + '.' + (who || P.slot) + '.json';
  a.hidden = false;
  document.getElementById('exportnote').textContent =
    reviews.length + ' of ' + P.items.length + ' rows returned. Rows you did '
    + 'not open are absent from the file and count as NOT REVIEWED, not as clean.';
});

paint();
"""


def render(slot: str, batch_id: str, items: list[dict[str, Any]]) -> str:
    payload = json.dumps(_payload(slot, batch_id, items), ensure_ascii=False)
    # `</script>` inside catalogue text would close the block early; `<` is
    # escaped rather than the exact sequence, because the exact sequence is one
    # of several that terminate a script element and the others are easy to
    # forget. JSON parses < identically.
    payload = payload.replace("<", "\\u003c").replace("&", "\\u0026")
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>CT-1 content review — {slot}</title>
<style>{CSS}</style>
</head>
<body>
<header>
  <h1>CT-1 content review</h1>
  <span class="muted">{batch_id} &middot; slot {slot}</span>
  <span class="grow"></span>
  <span id="progress" class="muted"></span>
</header>
<div class="wrap">
<nav id="nav" aria-label="Items"></nav>
<main>
  <section id="content"></section>
  <section>
    <div id="questions"></div>
    <h3>What is wrong (tick all that apply)</h3>
    <div id="reasons" class="reasons"></div>
    <h3>Note</h3>
    <textarea id="note" placeholder="Anything a reason code does not cover. Required if you tick &ldquo;Something else&rdquo;."></textarea>
    <div class="row">
      <label><input type="checkbox" id="domain"> Needs someone with domain
      knowledge to look at this</label>
    </div>
    <div class="row">
      <button class="act" id="prev">&larr; Previous</button>
      <button class="act" id="next">Next &rarr;</button>
      <span id="pos" class="muted"></span>
      <span class="grow"></span>
      <button class="act" id="skip">Skip this row</button>
    </div>
  </section>
  <section>
    <h3>Finish</h3>
    <div class="row">
      <label>Your name <input id="who" size="24" placeholder="first and last"></label>
      <button class="act primary" id="export">Export submission</button>
      <a id="dl" class="act" hidden>Download</a>
    </div>
    <p id="exportnote" class="muted"></p>
    <textarea id="out" hidden readonly></textarea>
  </section>
</main>
</div>
<script type="application/json" id="payload">{payload}</script>
<script>{JS}</script>
</body>
</html>
"""


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--batch", required=True, help="the batch directory")
    ap.add_argument("--out", default=None, help="defaults to <batch>/app")
    args = ap.parse_args(argv)

    batch = Path(args.batch)
    manifest = json.loads((batch / "manifest.json").read_text(encoding="utf-8"))
    # Dealing pages from a superseded batch would send a reviewer rows whose
    # assignments are not the live ones, and their submission would be refused
    # on import -- after the work had already been done.
    check_contract(manifest)
    assert_authoritative(manifest)
    items = json.loads((batch / "items.json").read_text(encoding="utf-8"))
    assignments = json.loads(
        (batch / "assignments.json").read_text(encoding="utf-8")
    )
    by_id = {i["item_id"]: i for i in items}

    out = Path(args.out) if args.out else batch / "app"
    out.mkdir(parents=True, exist_ok=True)
    for slot, ids in sorted(assignments["packages"].items()):
        page = render(slot, manifest["batch_id"], [by_id[i] for i in ids])
        path = out / f"review_{slot}.html"
        path.write_text(page, encoding="utf-8")
        print(f"{slot}: {len(ids):>3} items  ->  {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
