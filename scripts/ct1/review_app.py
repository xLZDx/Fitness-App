#: What each question means, in the words a reviewer reads.
#:
#: Every one is a comparison between two things visible on the page. None asks
#: whether the exercise is safe, appropriate, advisable or correct for anybody:
#: that is clinical authority, it is unreachable from this repository by
#: construction (see ``label_contract.CLINICALLY_VALIDATED_LABEL``), and a
#: question that invites the answer is exactly how a content label gets read as
#: a clinical one later. Section 9 and 10 of the brief; D1 and H3.
QUESTION_TEXT = {
    "title_matches_content": (
        "Does the title describe the movement the steps actually describe?"
    ),
    "content_is_complete": (
        "Are the steps a complete description, with nothing obviously missing "
        "or cut off mid-sentence?"
    ),
    "structure_is_consistent": (
        "Are the steps well formed — in a sensible order, not repeated, not "
        "broken formatting?"
    ),
    "instructions_are_consistent": (
        "Do the steps and tips agree with each other, rather than telling the "
        "reader two different things?"
    ),
    "content_is_not_duplicated": (
        "Is this text specific to this entry, rather than copied from another "
        "entry or repeated inside this one?"
    ),
    "equipment_matches_content": (
        "Does the listed equipment match the equipment the steps use?"
    ),
    "localisation_is_faithful": (
        "Does the Russian text say the same thing as the English, and is it "
        "actually translated?"
    ),
    "metadata_matches_content": (
        "Do the muscles, difficulty and stretch flag match what the steps "
        "describe?"
    ),
}

VERDICT_TEXT = {
    "ok": "OK",
    "problem": "Problem",
    "unsure": "Unsure",
}

REASON_TEXT = {
    "steps_missing": "Steps missing entirely",
    "steps_truncated": "Steps cut off / incomplete",
    "steps_out_of_order": "Steps in the wrong order",
    "steps_contradict_each_other": "Steps or tips contradict each other",
    "title_describes_different_movement": "Title is a different movement",
    "duplicate_of_another_row": "Copied from another entry",
    "duplicate_text_within_row": "Text repeated inside this entry",
    "equipment_not_used_by_steps": "Listed equipment is never used",
    "equipment_required_but_absent": "Steps need equipment that is not listed",
    "translation_missing": "Russian text missing",
    "translation_left_in_source_language": "Russian text is still English",
    "translation_changes_meaning": "Russian text says something else",
    "muscles_do_not_match_content": "Muscles do not match the movement",
    "difficulty_does_not_match_content": "Difficulty does not match",
    "formatting_broken": "Broken formatting / markup / encoding",
    "other": "Something else (write a note)",
}


def _payload(slot: str, batch_id: str, items: list[dict[str, Any]]) -> dict[str, Any]:
    """Exactly what the page is allowed to know.

    Built by naming the permitted fields rather than by removing forbidden ones.
    A denylist over an upstream dict leaks every field added after it was
    written; an allowlist fails closed, and the failure is a missing field
    somebody notices immediately rather than a leak nobody notices at all.
    """
    return {
        "batch_id": batch_id,
        "review_schema_version": REVIEW_SCHEMA_VERSION,
        "slot": slot,
        "questions": [
            {"id": q, "text": QUESTION_TEXT[q]} for q in REVIEW_QUESTIONS
        ],
        "verdicts": [{"id": v, "text": VERDICT_TEXT[v]} for v in VERDICTS],
        "reasons": [{"id": r, "text": REASON_TEXT[r]} for r in REASON_CODES],
        "items": [
            {
                "item_id": i["item_id"],
                "source_content_version": i["source_content_version"],
                "title": i.get("title"),
                "summary": i.get("summary"),
                "steps": list(i.get("steps") or []),
                "tips": list(i.get("tips") or []),
                "equipment_id": i.get("equipment_id"),
                "muscles": list(i.get("muscles") or []),
                "difficulty": i.get("difficulty"),
                "is_stretch": bool(i.get("is_stretch")),
                "ru": i.get("ru"),
            }
            for i in items
        ],
    }


