#!/usr/bin/env python3
"""Write docs/DOCUMENT_REGISTRY.md: a derived, deterministic listing of the
repository's Markdown documents (path, first heading, size). Stdlib only.

The registry never carries decisions; core/INDEX.md stays the canonical,
hand-maintained entry point and core/DECISION_LOG.md holds decisions.
Run from any directory: python scripts/dev/gen_document_registry.py
"""
from __future__ import annotations

import io
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SCAN_DIRS = ["docs", "core", "runbooks", "reports"]
TOP_FILES = ["README.md", "CLAUDE.md", "AGENTS.md", "FITNESS_APP_TASK_LIST.md"]
SKIP_PARTS = {"node_modules", ".git", "changes"}
# The registry itself, and the append-only decision log whose size changes with every commit.
SKIP_FILES = {"docs/DOCUMENT_REGISTRY.md", "core/DECISION_LOG.md"}
OUT = os.path.join(ROOT, "docs", "DOCUMENT_REGISTRY.md")


def first_heading(path: str) -> str:
    try:
        with io.open(path, encoding="utf-8", errors="replace") as fh:
            for line in fh:
                text = line.strip()
                if text.startswith("#"):
                    return text.lstrip("#").strip().replace("|", "/")[:120]
    except OSError:
        return ""
    return ""


def collect() -> list[tuple[str, str, int]]:
    rows: list[tuple[str, str, int]] = []
    for name in TOP_FILES:
        full = os.path.join(ROOT, name)
        if os.path.isfile(full):
            rows.append((name, first_heading(full), os.path.getsize(full)))
    for top in SCAN_DIRS:
        base = os.path.join(ROOT, top)
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames[:] = sorted(d for d in dirnames if d not in SKIP_PARTS)
            for fname in sorted(filenames):
                if not fname.lower().endswith(".md"):
                    continue
                full = os.path.join(dirpath, fname)
                rel = os.path.relpath(full, ROOT).replace(os.sep, "/")
                if rel in SKIP_FILES:
                    continue
                rows.append((rel, first_heading(full), os.path.getsize(full)))
    return sorted(rows)


def render(rows: list[tuple[str, str, int]]) -> str:
    lines = [
        "# Document registry (derived)",
        "",
        "Generated by `scripts/dev/gen_document_registry.py`. Do not edit by hand.",
        "Canonical entry point: `core/INDEX.md`. Decisions: `core/DECISION_LOG.md`.",
        "Per-commit change records under `core/changes/` are intentionally not listed.",
        "",
        "| Path | First heading | Bytes |",
        "|---|---|---|",
    ]
    for rel, title, size in rows:
        lines.append("| `%s` | %s | %d |" % (rel, title, size))
    lines.append("")
    return "\n".join(lines)


def check() -> int:
    """Exit 1 when the committed registry differs from a fresh render."""
    expected = render(collect())
    try:
        with io.open(OUT, encoding="utf-8", newline="") as fh:
            current = fh.read().replace("\r\n", "\n")
    except OSError:
        current = ""
    if current != expected:
        sys.stderr.write("docs/DOCUMENT_REGISTRY.md is stale: run scripts/dev/gen_document_registry.py\n")
        return 1
    sys.stdout.write("registry is up to date\n")
    return 0


def main() -> int:
    if "--check" in sys.argv[1:]:
        return check()
    rows = collect()
    with io.open(OUT, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render(rows))
    sys.stdout.write("wrote %s (%d documents)\n" % (os.path.relpath(OUT, ROOT), len(rows)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
