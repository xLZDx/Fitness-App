# -*- coding: utf-8 -*-
"""The shared MLOps primitive: a registry claim must match its cited report.

    python scripts/ml/evaluation_report.py            # audit
    python scripts/ml/evaluation_report.py --json
    python -m pytest scripts/ml/test_evaluation_report.py -q

## Why this exists, and why it is this and not a schema

`core/ml/MODEL_REGISTRY.json` states measured numbers inline — `top_3: 0.835`,
`coverage: 0.443` — and separately names an `evaluation_report` the numbers came
from. Nothing checked that the two agree. A registry that quotes a figure its
own cited source does not contain is worse than one that quotes nothing: the
citation makes it look verified.

The obvious primitive was a shared `EVALUATION_REPORT_MANIFEST` schema that
every producer emits. It was **not** built, for a measured reason. There are two
real consumers — `equipment_recognition` and `content_qa` — and their reports
are in different media on purpose:

* `content_qa` is generated by `scripts/ct1/evaluate.py` and is already JSON.
* `equipment_recognition` is a **prose** report at
  `mobile/assets/models/README.md`, and it is a genuine one: a held-out 15%
  stratified split, n=261, per-class breakdown, and a post-mortem of a leak the
  pipeline caught. Its numbers were produced by a pipeline that is not in this
  repository (see `scanner_provenance.py`, ML-2a), so nothing here can re-emit
  them in any format.

A schema every producer emits would therefore have exactly one producer. What
both consumers DO share is the thing that can actually go wrong: the registry's
copy of a number drifting from the report it cites. So the shared primitive is
the CHECK, not the format.

## The anti-vacuity rule this module lives under

A locator that finds nothing must report `NOT_LOCATABLE`, never `MATCHES`. A
checker that silently fails to parse its source and reports no drift is the
defect it exists to prevent, wearing the costume of a passing test. Every
verdict below therefore says which claims it could not find, and the audit's
exit code counts those separately from drift.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[2]
REGISTRY = REPO / "core" / "ml" / "MODEL_REGISTRY.json"

#: What the audit can conclude about one quoted metric.
#:
#: `NOT_LOCATABLE` is deliberately not merged into `DRIFTED`. Drift means the
#: source says something different; not-locatable means this module could not
#: read the source well enough to say. Reporting the second as the first would
#: cry wolf; reporting it as a match would be the vacuous guard.
VERDICTS = ("MATCHES", "DRIFTED", "NOT_LOCATABLE", "SOURCE_MISSING")

#: How a metric name may be written in a prose report.
#:
#: Only substitutions that are spelling, never meaning. `top_1` and `top-1` are
#: the same measurement; `top_1` and `accuracy` are not, and this must never be
#: taught to treat them as such.
_NAME_VARIANTS = {
    "_": ["_", "-", " ", ""],
}

#: How far from the metric's name its value may sit and still be that metric's
#: value. Sized against the real sources: the widest genuine gap is the aligned
#: code block in the scanner README, where the label and the number are 38
#: characters apart.
WINDOW = 120


def _name_forms(metric: str) -> list[str]:
    """Every spelling of a metric name that means the same measurement."""
    forms = {metric}
    for sep in _NAME_VARIANTS["_"]:
        forms.add(metric.replace("_", sep))
    return sorted(forms)


def _value_forms(value: float | int) -> list[str]:
    """Every rendering of a value that a report might legitimately use.

    A ratio is written as `0.835`, `.835` or `83.5%` depending on the author,
    and a count as `18`. Percentages are included because both real sources use
    them; rounding to a shorter decimal is NOT, because `0.83` and `0.835` are
    different claims and a checker that accepts either cannot detect a drift
    into the third digit.
    """
    forms: set[str] = set()
    if isinstance(value, bool):
        return [str(value)]
    if isinstance(value, int):
        forms.add(str(value))
    else:
        text = repr(float(value))
        forms.add(text)
        if text.startswith("0."):
            forms.add(text[1:])
        pct = float(value) * 100
        if abs(pct - round(pct)) < 1e-9:
            forms.add("%d%%" % round(pct))
        else:
            forms.add(("%s" % round(pct, 4)).rstrip("0").rstrip(".") + "%")
    return sorted(forms)


def locate(source: str, metric: str, value: float | int) -> bool:
    """Does [source] state that [metric] is [value]?

    Name and value must appear within [WINDOW] characters of each other, in
    either order — a report may write `top-3 = 0.835` or `0.835 top-3`.
    """
    lowered = source.lower()
    for name in _name_forms(metric.lower()):
        if not name:
            continue
        for start in _positions(lowered, name):
            window = source[max(0, start - WINDOW):start + WINDOW]
            for form in _value_forms(value):
                if form in window:
                    return True
    return False


def _positions(haystack: str, needle: str) -> list[int]:
    out, i = [], haystack.find(needle)
    while i >= 0:
        out.append(i)
        i = haystack.find(needle, i + 1)
    return out


def _flatten(payload: Any, prefix: str = "") -> dict[str, Any]:
    """Every scalar in a JSON report, by dotted path."""
    out: dict[str, Any] = {}
    if isinstance(payload, dict):
        for k, v in payload.items():
            out.update(_flatten(v, f"{prefix}.{k}" if prefix else k))
    elif isinstance(payload, list):
        for i, v in enumerate(payload):
            out.update(_flatten(v, f"{prefix}[{i}]"))
    else:
        out[prefix] = payload
    return out


def check_claim(source_text: str, is_json: bool, metric: str,
                value: Any) -> str:
    """One quoted metric against the report it cites."""
    if value is None:
        # A null is not a claim. `content_qa` carries `precision: null` on
        # purpose -- EVALUATION_LABEL_GAP -- and demanding a source for the
        # absence of a number would be demanding evidence of a negative.
        return "MATCHES"
    if not isinstance(value, (int, float)) or isinstance(value, bool):
        return "NOT_LOCATABLE"

    if is_json:
        scalars = _flatten(json.loads(source_text))
        tail = metric.rsplit(".", 1)[-1]
        hits = [v for k, v in scalars.items() if k.rsplit(".", 1)[-1] == tail]
        if not hits:
            # Fall through to the text search: a JSON report may name the same
            # measurement differently, and refusing to look would report a
            # readable source as unreadable.
            return "MATCHES" if locate(source_text, metric, value) \
                else "NOT_LOCATABLE"
        return "MATCHES" if any(_same(h, value) for h in hits) else "DRIFTED"

    if locate(source_text, metric, value):
        return "MATCHES"
    # Distinguish "the source discusses this metric and says something else"
    # from "this module could not find the metric at all".
    named = any(_positions(source_text.lower(), n)
                for n in _name_forms(metric.lower()) if n)
    return "DRIFTED" if named else "NOT_LOCATABLE"


def _same(a: Any, b: Any) -> bool:
    if isinstance(a, bool) or isinstance(b, bool):
        return a is b
    if isinstance(a, (int, float)) and isinstance(b, (int, float)):
        return abs(float(a) - float(b)) < 1e-9
    return a == b


#: Keys of an evaluation entry that are not measurements.
#:
#: Everything else numeric IS a claim, including one written flat rather than
#: under `metrics`. Both shapes are in the registry today -- the scanner nests,
#: `content_qa` does not -- and a checker that read only the nested shape would
#: have silently skipped every number the second consumer states, which is
#: precisely the vacuous-guard failure this module is written against.
NOT_A_METRIC = frozenset({
    "dataset", "dataset_hash", "caveat", "source", "note", "notes",
})


def claims_of(evaluation: dict[str, Any]) -> dict[str, Any]:
    """Every number an evaluation entry asserts, in either shape."""
    out: dict[str, Any] = {}
    for key, value in evaluation.items():
        if key.startswith("$") or key in NOT_A_METRIC or key == "metrics":
            continue
        if value is None or isinstance(value, (int, float)):
            out[key] = value
    out.update(evaluation.get("metrics") or {})
    return out


def audit(registry: Path | None = None) -> dict[str, Any]:
    """Every quoted metric in the model registry, against its cited report."""
    path = Path(registry or REGISTRY)
    payload = json.loads(path.read_text(encoding="utf-8"))
    findings: list[dict[str, Any]] = []
    cache: dict[str, tuple[str, bool] | None] = {}

    for entry in payload.get("models", []):
        cited = entry.get("evaluation_report")
        model = entry.get("model_id", "?")
        version = entry.get("model_version") or entry.get("version") or "?"
        evaluations = entry.get("evaluations") or []

        if cited is None:
            for i, ev in enumerate(evaluations):
                for metric, value in claims_of(ev).items():
                    findings.append(_finding(model, version, i, metric, value,
                                             None, "SOURCE_MISSING"))
            continue

        if cited not in cache:
            source = REPO / cited
            cache[cited] = (
                (source.read_text(encoding="utf-8"), source.suffix == ".json")
                if source.exists() else None
            )
        loaded = cache[cited]

        for i, ev in enumerate(evaluations):
            # An evaluation may name its OWN source. The model-level
            # `evaluation_report` is the report for the model; a single
            # evaluation inside it can come from somewhere else entirely --
            # the scanner's real-world measurement does, and checking those
            # numbers against a document that never contained them would
            # report a citation problem as a drift problem.
            per_eval = ev.get("source") or cited
            if per_eval not in cache:
                src = REPO / per_eval
                cache[per_eval] = (
                    (src.read_text(encoding="utf-8"), src.suffix == ".json")
                    if src.exists() else None
                )
            here = cache[per_eval]
            for metric, value in claims_of(ev).items():
                if here is None:
                    verdict = "SOURCE_MISSING"
                else:
                    verdict = check_claim(here[0], here[1], metric, value)
                findings.append(
                    _finding(model, version, i, metric, value, per_eval,
                             verdict))

    counts = {v: sum(1 for f in findings if f["verdict"] == v) for v in VERDICTS}
    try:
        shown = str(path.relative_to(REPO)).replace("\\", "/")
    except ValueError:
        # A registry outside the repository: a test fixture, or somebody
        # auditing a copy. Report the path it actually read rather than
        # refusing to report at all.
        shown = str(path)
    return {
        "registry": shown,
        "claims": len(findings),
        "counts": counts,
        "findings": findings,
        "drifted": [f for f in findings if f["verdict"] == "DRIFTED"],
        "unlocatable": [f for f in findings if f["verdict"] == "NOT_LOCATABLE"],
    }


def _finding(model, version, index, metric, value, cited, verdict):
    return {
        "model_id": model,
        "version": version,
        "evaluation_index": index,
        "metric": metric,
        "claimed": value,
        "cited_report": cited,
        "verdict": verdict,
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--json", action="store_true")
    ap.add_argument("--registry", default=None)
    args = ap.parse_args(argv)

    result = audit(args.registry)
    if args.json:
        print(json.dumps(result, ensure_ascii=False, indent=2, sort_keys=True))
    else:
        print(f"  {result['claims']} quoted metrics in {result['registry']}")
        for verdict in VERDICTS:
            print(f"  {verdict:<16} {result['counts'][verdict]}")
        for f in result["drifted"]:
            print(f"\n  DRIFT  {f['model_id']} {f['metric']} = {f['claimed']}")
            print(f"         {f['cited_report']} says otherwise")
        for f in result["unlocatable"]:
            print(f"\n  UNREADABLE  {f['model_id']} {f['metric']} = "
                  f"{f['claimed']}")
            print(f"              not found in {f['cited_report']}")

    # Drift fails. Unlocatable does NOT fail the command -- it is a gap in this
    # module's reach, not a defect in the registry, and conflating the two
    # would make the honest report of a limitation look like an accusation.
    return 1 if result["drifted"] else 0


if __name__ == "__main__":
    raise SystemExit(main())
