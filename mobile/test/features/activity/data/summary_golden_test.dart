// S02-01 U30: golden summaries drift guard. The file is the one the rules test
// R25 loads; timestamps are ISO-8601 UTC strings. Regenerated only with
// S02_UPDATE_GOLDEN=1, otherwise compared.
import 'dart:convert';

import 'package:fitness_app/features/activity/data/activity_cloud_summary.dart';
import 'package:flutter_test/flutter_test.dart';

import '../../../support/firestore_rules_parser.dart';
import '../../../support/s02_paths.dart';
import '../../../support/synthetic_activity_corpus.dart';

Map<String, Object?> _generate() {
  final c = SyntheticCorpus.build();
  return {
    'version': 1,
    'note': 'Cloud summaries (rev 1) of the 100 synthetic sessions; timestamps are ISO-8601 UTC strings. Generated by mobile/test/features/activity/data/summary_golden_test.dart.',
    'summaries': [
      for (final s in c.valid)
        {
          'id': s.id,
          'summary': {
            for (final e in ActivityCloudSummary.fromSession(s).entries)
              e.key: e.value is DateTime
                  ? (e.value as DateTime).toUtc().toIso8601String()
                  : e.value,
          },
        },
    ],
  };
}

void main() {
  final file = repoFile('functions/src/__rules__/fixtures/s02_summaries_100.json');

  test('regenerated summaries equal the committed golden file', () {
    final generated = canonicalJson(_generate());
    if (updateGolden) {
      file.parent.createSync(recursive: true);
      file.writeAsStringSync(
          '${const JsonEncoder.withIndent(' ').convert(jsonDecode(generated))}\n');
    }
    expect(file.existsSync(), isTrue,
        reason: 'run once with S02_UPDATE_GOLDEN=1 to create the golden file');
    final committed = canonicalJson(jsonDecode(file.readAsStringSync()));
    expect(committed, generated, reason: 'summaries drifted from the golden file');
  });

  test('the golden file is sound: 100 distinct ids, rev 1, accepted by the rules shape',
      () {
    final rules = parseActivityRules();
    final doc = jsonDecode(file.readAsStringSync()) as Map<String, dynamic>;
    final list = doc['summaries'] as List;
    expect(list, hasLength(100));
    expect({for (final e in list) e['id']}, hasLength(100));
    for (final e in list) {
      final m = Map<String, Object?>.from(e['summary'] as Map);
      expect(m['rev'], 1);
      expect(RegExp(r'^act_[0-9a-f]{40}$').hasMatch(e['id'] as String), isTrue);
      final shape = {
        for (final k in m.keys)
          k: (k == 'startUtc' || k == 'endUtc' || k == 'updatedAt')
              ? DateTime.parse(m[k] as String)
              : m[k],
      };
      expect(rulesViolations(rules, shape.cast<String, Object?>()), isEmpty, reason: e['id'] as String);
    }
  });

  test('a drifted golden would be detected (negative control)', () {
    final generated = _generate();
    final tampered = jsonDecode(jsonEncode(generated)) as Map<String, dynamic>;
    ((tampered['summaries'] as List)[0]['summary'] as Map)['distanceM'] = 1.0;
    expect(canonicalJson(tampered), isNot(canonicalJson(generated)));
  });
}
